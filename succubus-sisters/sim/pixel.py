def render(key):
  bg, rows = ART[key]
  c1, c2 = BG[bg]
  im = Image.new('RGB', (W, H))
  rnd = random.Random(key)
  stars = {(rnd.randrange(W), rnd.randrange(H - 3)) for _ in range(6)}
  px = im.load()
  svg = []
  for y in range(H):
    for x in range(W):
      t = (y / (H - 1))
      col = tuple(int(c1[i] * (1 - t) + c2[i] * t) for i in range(3))
      if (x, y) in stars and rows[y][x] == '.': col = (120, 110, 140)
      ch = rows[y][x]
      if ch != '.': col = PAL[ch]
      px[x, y] = col
      svg.append(f'<rect x="{x}" y="{y}" width="1" height="1" fill="#{col[0]:02x}{col[1]:02x}{col[2]:02x}"/>')
  im.resize((W * S, H * S), Image.NEAREST).save(os.path.join(OUT, key + '.png'))
  open(os.path.join(OUT, key + '.svg'), 'w').write(
    f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" shape-rendering="crispEdges">' + ''.join(svg) + '</svg>')

for k in ART: render(k)
